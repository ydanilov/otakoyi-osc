/**
 * `docs/pult-capacity.md`: how much fits one pult screen, computed with the pult's own
 * `layoutPage`, `naturalHeightFor`, `panelMinHeight` and the token sizes. Generated, never edited
 * by hand; `pnpm pult-capacity:check` (part of `pnpm verify`) fails when it is stale.
 */
import { FORM_FACTORS, PANEL_PATTERNS, type FormFactor, type PanelPattern } from "@osc/schema";
import { naturalHeightFor, panelMinHeight, pultMetrics } from "@osc/ui/pult/layout";
import { shapeOf, type Shape } from "./controls";
import { fitsOneScreen, REFERENCE, sizes } from "./plan";

interface Sample {
  name: string;
  control: Record<string, unknown>;
}

/** One sample per control kind, as the draft places it (see `controlFor`). */
const SAMPLES: Sample[] = [
  { name: "Fader (horizontal)", control: { type: "fader", orientation: "horizontal" } },
  { name: "Knob", control: { type: "knob" } },
  { name: "Knob (compact)", control: { type: "knob", size: "compact" } },
  { name: "Toggle switch", control: { type: "toggle", style: "switch" } },
  { name: "Pad, regular (toggle / button)", control: { type: "button", size: "regular" } },
  { name: "Pad, compact", control: { type: "button", size: "compact" } },
  { name: "Hold to confirm", control: { type: "holdToConfirm" } },
  { name: "Segmented (with label)", control: { type: "segmented", label: "Mode" } },
  { name: "XY pad / colour picker / list (stretch)", control: { type: "xy" } },
];

const MIXES: Array<{ name: string; parts: Array<[Sample["control"], number]> }> = [
  {
    name: "2 faders + 2 toggle switches (a tuning block)",
    parts: [
      [{ type: "fader", orientation: "horizontal" }, 2],
      [{ type: "toggle", style: "switch" }, 2],
    ],
  },
  {
    name: "1 segmented + 2 pads + 1 fader (a live block)",
    parts: [
      [{ type: "segmented", label: "Mode" }, 1],
      [{ type: "button", size: "regular" }, 2],
      [{ type: "fader", orientation: "horizontal" }, 1],
    ],
  },
  {
    name: "1 XY pad + 2 faders",
    parts: [
      [{ type: "xy" }, 1],
      [{ type: "fader", orientation: "horizontal" }, 2],
    ],
  },
];

const PANEL_COUNTS: Partial<Record<PanelPattern, number[]>> = {
  knobGroup: [2, 4, 6],
  list: [3, 5, 8],
  stack: [2, 3, 4],
};

const asUnits = (controls: Record<string, unknown>[], group = "g") =>
  controls.map((c, i) => {
    const control = { id: `c${i}`, label: "Label", address: `/a/${i}`, ...c };
    return { id: control.id, shape: shapeOf(control as never) as Shape, group, control };
  });

/** Largest n such that n copies of `make(n)` fit one screen (capped). */
function maxFit(make: (n: number) => Record<string, unknown>[], ff: FormFactor, cap = 60): number {
  let n = 0;
  while (n < cap && fitsOneScreen(asUnits(make(n + 1)), ff)) n++;
  return n;
}

const fmt = (n: number, cap = 60) => (n >= cap ? `${cap}+` : String(n));

export function capacityMarkdown(): string {
  const L: string[] = [];
  L.push("# Pult capacity");
  L.push("");
  L.push(
    "<!-- Generated by `pnpm pult-capacity` (tools/pult-plan/src/capacity.ts). Do not edit by hand; `pnpm verify` fails when this file is stale. -->",
  );
  L.push("");
  L.push(
    "How many controls fit one pult screen before the pult splits the page into another screen " +
      "(ADR-006: the pult never scrolls vertically). Every number comes from the pult's own " +
      "`layoutPage`, `naturalHeightFor` and `panelMinHeight` (`packages/ui/src/pult/layout.ts`) " +
      "and the token sizes (`packages/tokens/tokens.json`), with controls placed the way " +
      "`pnpm pult-draft` places them. Use `pnpm pult-plan --contract <path>` to see the split for " +
      "a real installation.",
  );
  L.push("");
  L.push("## Reference devices");
  L.push("");
  L.push("| Form factor | Device | Pult body (pt) | Gap | Padding (x / top / bottom) |");
  L.push("| --- | --- | --- | --- | --- |");
  for (const ff of FORM_FACTORS) {
    const r = REFERENCE[ff];
    const m = pultMetrics(ff, sizes);
    L.push(
      `| ${ff} | ${r.device} | ${r.width} × ${r.height} | ${m.gap} | ${m.padX} / ${m.padTop} / ${m.padBottom} |`,
    );
  }
  L.push("");
  L.push(
    "The pult body is the area under the pult header (Figma: phone _Pult_ frame, tablet _Console_ frame).",
  );
  L.push("");
  L.push("## Draft grid");
  L.push("");
  L.push("| Shape | Controls | Phone cell (cols × rows) | Tablet cell (cols × rows) |");
  L.push("| --- | --- | --- | --- |");
  L.push(
    "| half | toggle, button, hold to confirm, knob | 6 × 2 (two per row) | 2 × 2 (six per row) |",
  );
  L.push("| full | horizontal fader, segmented, label | 12 × 2 | 4 × 2 (three per row) |");
  L.push(
    "| stretch | XY pad, colour picker, list (sceneList), button grid, prompt, vertical fader | 12 × 6 | 4 × 6 |",
  );
  L.push("");
  L.push(
    "Stretchable controls get at least 40 pt per grid row (`MIN_ROW`) before a split, then share the free height.",
  );
  L.push("");
  L.push("## One control type per screen");
  L.push("");
  L.push("| Control | Height (pt) | Phone | Tablet |");
  L.push("| --- | --- | --- | --- |");
  for (const s of SAMPLES) {
    const h = naturalHeightFor({ id: "x", label: "Label", ...s.control } as never, sizes);
    const row = FORM_FACTORS.map((ff) => fmt(maxFit((n) => Array(n).fill(s.control), ff)));
    L.push(`| ${s.name} | ${h ?? "stretches"} | ${row.join(" | ")} |`);
  }
  L.push("");
  L.push("## Typical mixes (blocks per screen)");
  L.push("");
  L.push("| Block | Phone | Tablet |");
  L.push("| --- | --- | --- |");
  for (const mix of MIXES) {
    const block = mix.parts.flatMap(([c, n]) => Array(n).fill(c));
    const row = FORM_FACTORS.map((ff) =>
      fmt(
        maxFit((n) => Array.from({ length: n }, () => block).flat(), ff, 20),
        20,
      ),
    );
    L.push(`| ${mix.name} | ${row.join(" | ")} |`);
  }
  L.push("");
  L.push("## Console panels (Figma patterns)");
  L.push("");
  L.push("| Pattern | Controls | Height (pt) |");
  L.push("| --- | --- | --- |");
  for (const p of PANEL_PATTERNS) {
    const counts = PANEL_COUNTS[p] ?? [p === "faderBank" ? 4 : 1];
    for (const n of counts)
      L.push(
        `| ${p} | ${PANEL_COUNTS[p] ? n : "—"} | ${panelMinHeight(p, n)}${p === "faderBank" ? " (minimum; stretches)" : ""} |`,
      );
  }
  L.push("");
  L.push("## Split rule");
  L.push("");
  L.push(
    "- Controls are packed from the top at their Figma heights with the form factor's gap; stretchable controls share what is left (tablet: the last item of every column stretches to the bottom).",
  );
  L.push(
    "- Controls that share grid rows form a band. A band that does not fit under the previous ones starts a new screen; a band is never cut. A single band taller than a screen is scaled down.",
  );
  L.push(
    "- `pult-draft` and `pult-plan` add one rule on top: a contract group is never split across screens unless the group alone is bigger than a screen (then it splits where `layoutPage` splits it). `live` parameters come first, then `tune`; `setup` goes to a separate Setup pult; `hidden` is left out.",
  );
  L.push("");
  return L.join("\n");
}
